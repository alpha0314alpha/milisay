#include <iostream>
#include <vector>
using namespace std;
const size_t MAX_LEN = 20;

const string MILI[] = {
    R"(............................................)",
    R"(..............################..............)",
    R"(..........########################..........)",
    R"(........############################........)",
    R"(......################################......)",
    R"(......################################......)",
    R"(....####################################....)",
    R"(....####################################....)",
    R"(....######################################..)",
    R"(..#########################################.)",
    R"(.#######################################....)",
    R"(....####################################....)",
    R"(....####################################....)",
    R"(....####################################....)",
    R"(......################################......)",
    R"(......################################......)",
    R"(........############################........)",
    R"(..........########################..........)",
    R"(..............################..............)",
    R"(............................................)"
};

int main(){
    string input;
    cin >> input;
    size_t width = min(MAX_LEN, input.size());
    vector<string> sub;
    for (size_t i = 0; i < input.size(); i += width){
        sub.push_back(input.substr(i, width));
    }

    cout << '/' << string(width, '-') << "\\\n";
    for (string s : sub){
        cout << '|' << s << string(width-s.size(), ' ') << "|\n";
    }
    cout << '\\' << string(width, '-') << "/\n";

    for (string s : MILI) cout << s << '\n';
    return 0;
}
